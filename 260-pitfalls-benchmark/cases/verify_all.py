"""Verify every case: run gen, flaw (per variant), EXPLAIN (plan.txt), df variants, fixed.

Usage: ../venv/py4/bin/python verify_all.py [--only NN]   (from cases/)
Writes ../verification-log.md and per-case plan.txt.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent

from pyspark.sql import SparkSession, functions as F  # noqa: E402


def rows_of(df: Any) -> list[Any]:
    return [tuple(r) for r in df.collect()]


def show(rows: list[Any]) -> str:
    if len(rows) > 5:
        return f"{rows[:3]} ... (+{len(rows) - 3} more rows, total {len(rows)})"
    return str(rows)


def run_sql(spark: Any, q: str) -> str:
    try:
        return f"OK {show(rows_of(spark.sql(q)))}"
    except Exception as e:  # noqa: BLE001
        return f"ERR {type(e).__name__}: {str(e).splitlines()[0][:200]}"


def main() -> None:
    only = None
    if "--only" in sys.argv:
        only = sys.argv[sys.argv.index("--only") + 1]
    spark = (
        SparkSession.builder.master("local[1]").appName("task260-verify")
        .config("spark.sql.shuffle.partitions", "4").config("spark.ui.enabled", "false")
        .config("spark.sql.session.timeZone", "UTC").getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")
    log: list[str] = [
        "# Verification log (auto-generated by cases/verify_all.py)",
        f"spark {spark.version}; each case: gen.sql, flaw.sql per tz variant, df variants, fixed.sql",
        "",
    ]
    for d in sorted(HERE.iterdir()):
        if not d.is_dir() or not (d / "case.json").exists():
            continue
        meta = json.loads((d / "case.json").read_text(encoding="utf-8"))
        if only and meta["n"] != only:
            continue
        log.append(f"## Case {meta['n']} {meta['name']} ({meta['difficulty']}, {meta['category']}, pitfall {meta['pitfall']})")
        gen = (d / "gen.sql").read_text(encoding="utf-8")
        for stmt in [s.strip() for s in gen.split(";\n") if s.strip()]:
            log.append(f"gen: {run_sql(spark, stmt)}")
        flaw = (d / "flaw.sql").read_text(encoding="utf-8").strip().rstrip(";")
        fixed = (d / "fixed.sql").read_text(encoding="utf-8").strip().rstrip(";")
        try:
            plan = spark.sql(f"EXPLAIN EXTENDED {flaw}").collect()[0][0]
            norm = "\n".join(l for l in plan.splitlines() if l.strip())
            (d / "plan.txt").write_text(norm, encoding="utf-8")
            log.append(f"plan.txt written ({len(norm.splitlines())} lines after EXPLAIN EXTENDED)")
        except Exception as e:  # noqa: BLE001
            log.append(f"plan: ERR {str(e).splitlines()[0][:150]}")
        for v in meta.get("variants", [{"tz": "UTC"}]):
            spark.conf.set("spark.sql.session.timeZone", v.get("tz", "UTC"))
            log.append(f"flaw (tz={v.get('tz', 'UTC')}): {run_sql(spark, flaw)}")
            log.append(f"fixed (tz={v.get('tz', 'UTC')}): {run_sql(spark, fixed)}")
        for expr in meta.get("df_variants", []):
            try:
                val = eval(expr, {"spark": spark, "F": F})  # noqa: S307 - our own case files
                log.append(f"df variant `{expr}` -> {val if not hasattr(val, 'collect') else show(rows_of(val))}")
            except Exception as e:  # noqa: BLE001
                log.append(f"df variant `{expr}` -> ERR {str(e).splitlines()[0][:150]}")
        spark.conf.set("spark.sql.session.timeZone", "UTC")
        log.append("")
    out = HERE.parent / ("verification-log.md" if not only else f"verification-log-partial-{only}.md")
    out.write_text("\n".join(log) + "\n", encoding="utf-8")
    print(f"wrote {out}; cases: {sum(1 for l in log if l.startswith('## '))}")


if __name__ == "__main__":
    main()
